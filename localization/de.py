def translate_de(value: object) -> str:
    """Translate presentation copy while preserving numeric/source identities."""
    text = str(value)
    if text.startswith(("http://", "https://")):
        return text
    if text in EXACT_DE:
        return EXACT_DE[text]
    if text in TOPIC_DE:
        return TOPIC_DE[text]
    if text in EVIDENCE_DE:
        return EVIDENCE_DE[text]
    if text in QUOTE_DE:
        return QUOTE_DE[text]
    translated = text
    for english, german in sorted(PHRASE_DE, key=lambda pair: len(pair[0]), reverse=True):
        pattern = rf"(?<![A-Za-z0-9_]){re.escape(english)}(?![A-Za-z0-9_])"
        translated = re.sub(pattern, lambda _match, replacement=german: replacement, translated)
    return translated


def localize_tex(source: str, extra_exact: dict[str, str] | None = None) -> str:
    """Localize human-facing strings inside generated LaTeX without touching IDs."""
    replacements = dict(PHRASE_DE)
    replacements.update(EXACT_DE)
    replacements.update(QUOTE_DE)
    replacements["Menu \\& Tablet"] = "Speisekarte \\& Tablet"
    replacements["Menu \\& Ordering"] = "Speisekarte \\& Bestellung"
    replacements["Price \\& Value"] = "Preis-Leistungs-Verhältnis"
    replacements["Reputation \\& Data"] = "Reputation \\& Daten"
    replacements["Menu, Bar \\& Offers"] = "Speisekarte, Bar \\& Angebote"
    replacements["Kitchen \\& Buffet Quality"] = "Küche \\& Buffetqualität"
    replacements["Kitchen \\& Buffet"] = "Küche \\& Buffet"
    replacements["Terrace \\& Outdoor Seating"] = "Terrasse \\& Außenplätze"
    replacements["Burgers \\& Western Dishes"] = "Burger \\& westliche Gerichte"
    replacements["Shawarma \\& Sandwiches"] = "Shawarma und Sandwiches"
    replacements["Sehr lecker appetizer platter \\& delectable desserts, followed by Arabic mocha."] = (
        "Sehr leckere Vorspeisenplatte und köstliche Desserts, gefolgt von arabischem Mokka."
    )
    if extra_exact:
        replacements.update(extra_exact)
    protected: dict[str, str] = {}

    def protect(match: re.Match[str]) -> str:
        token = f"@@DEPROTECTED{len(protected)}@@"
        protected[token] = match.group(0)
        return token

    # TeX commands, pgfplots selectors and file paths are identifiers, not copy.
    result = re.sub(r"\\\\", protect, source)
    result = re.sub(r"\\[A-Za-z@]+", protect, result)
    result = re.sub(r"symbolic [xy] coords=\{[^}]*\}", protect, result)
    result = re.sub(r"coordinates\s*\{[^}]*\}", protect, result)
    result = re.sub(r"(?<![A-Za-z])(?:x|y)=[A-Za-z_]+", protect, result)
    result = re.sub(r"(?:draw|fill)=none", protect, result)
    result = re.sub(r"assets/[A-Za-z0-9_.-]+", protect, result)
    translated_tokens: dict[str, str] = {}
    for english, german in sorted(replacements.items(), key=lambda pair: len(pair[0]), reverse=True):
        pattern = rf"(?<![A-Za-z0-9_]){re.escape(english)}(?![A-Za-z0-9_])"
        def translate_match(_match: re.Match[str], replacement: str = german) -> str:
            token = f"@@DETRANSLATED{len(translated_tokens)}@@"
            translated_tokens[token] = replacement
            return token
        result = re.sub(pattern, translate_match, result)
    for english, german in sorted(TOPIC_DE.items(), key=lambda pair: len(pair[0]), reverse=True):
        pattern = rf"(?<![\\A-Za-z0-9_]){re.escape(english)}(?![A-Za-z0-9_])"
        result = re.sub(pattern, lambda _match, replacement=german: replacement, result)
    for token, translated in reversed(list(translated_tokens.items())):
        result = result.replace(token, translated)
    for token, original in reversed(list(protected.items())):
        result = result.replace(token, original)
    return result
